"""Turns .tmod files into the C++ table of the built-in modules (OS-012d, module/include/o3os/module/builtin.h).

    o3m_embed.py --out <file.cpp> --notice <file>... [<stem>=<file.tmod>...]

The bytes of each file go into a const array (flash on the MK66) and the table lists them in the order given; the notice files are joined into one NUL terminated string
(kBuiltinNotices: the licence text the modules' code requires the image to carry). Nothing is parsed or changed: the loader validates the file exactly as it does from the
card. Stdlib only.
"""
import argparse
import re
import sys


def cpp_string(text: bytes) -> str:
    out = []
    for line in text.decode("utf-8").replace("\r\n", "\n").split("\n"):
        out.append('    "' + line.replace("\\", "\\\\").replace('"', '\\"') + '\\n"')
    return "\n".join(out)


def generate(modules, notices) -> str:
    lines = [
        "// SPDX-License-Identifier: GPL-3.0-or-later",
        "// Generated by tools/o3m_embed.py from the built .tmod files (OS-012d). Do not edit.",
        "#include <o3os/module/builtin.h>",
        "",
        "namespace o3os::module {",
        "namespace {",
    ]
    for stem, data in modules:
        lines.append(f"// {stem}.tmod, {len(data)} bytes")
        lines.append(f"alignas(4) const std::uint8_t k_{stem}[{len(data)}] = {{")
        for i in range(0, len(data), 24):
            lines.append("    " + ",".join(str(b) for b in data[i:i + 24]) + ",")
        lines.append("};")
    lines.append("}  // namespace")
    lines.append("")
    lines.append("const BuiltinModule kBuiltinModules[] = {")
    for stem, data in modules:
        lines.append(f'    {{"{stem}", k_{stem}, {len(data)}u}},')
    if not modules:
        lines.append("    {nullptr, nullptr, 0u},  // no .tmod was built (no cross compiler): the count says 0")
    lines.append("};")
    lines.append(f"const unsigned kBuiltinModuleCount = {len(modules)};")
    lines.append("")
    lines.append("const char kBuiltinNotices[] =")
    lines.append(cpp_string(notices) + ";")
    lines.append("}  // namespace o3os::module")
    return "\n".join(lines) + "\n"


def main(argv) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", required=True)
    ap.add_argument("--notice", action="append", default=[])
    ap.add_argument("modules", nargs="*", help="<stem>=<file.tmod>")
    args = ap.parse_args(argv)
    mods = []
    for spec in args.modules:
        stem, _, path = spec.partition("=")
        if not re.fullmatch(r"[A-Za-z0-9_]{1,31}", stem) or not path:
            print(f"o3m_embed: bad module spec '{spec}' (stem=file, stem of letters, digits and _)", file=sys.stderr)
            return 2
        with open(path, "rb") as f:
            data = f.read()
        if len(data) < 64 or len(data) % 4 != 0:
            print(f"o3m_embed: {path} is not a .tmod file (size {len(data)})", file=sys.stderr)
            return 2
        mods.append((stem, data))
    notices = b""
    for path in args.notice:
        with open(path, "rb") as f:
            notices += f.read().rstrip() + b"\n\n"
    with open(args.out, "w", encoding="utf-8", newline="\n") as f:
        f.write(generate(mods, notices.rstrip() + b"\n"))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
